def test_rouge_l_identical_is_one():
    r = rouge_l("the cat sat on the mat", "the cat sat on the mat")
    assert r["f"] == pytest.approx(1.0)
    assert r["lcs"] == 6


def test_rouge_l_disjoint_is_zero():
    r = rouge_l("alpha beta", "gamma delta")
    assert r["f"] == 0.0 and r["lcs"] == 0


def test_rouge_l_precision_and_recall_differ_by_length():
    """A long candidate scores higher recall, which is the trap in 3.3."""
    # `cat` finds one token in a six-token reference: perfect precision,
    # terrible recall. Padding the candidate out finds the same tokens in a
    # longer string: perfect recall, worse precision — and a *higher* F, even
    # though the padded answer is the worse answer.
    short = rouge_l("cat", "the cat sat on the mat")
    long = rouge_l(
        "the cat sat on the mat and then it sat on another mat too",
        "the cat sat on the mat")
    assert short["precision"] == pytest.approx(1.0)
    assert short["recall"] == pytest.approx(1 / 6)
    assert long["recall"] == pytest.approx(1.0)
    assert long["precision"] < 1.0
    # The padded, content-identical answer wins on overlap. That is the point.
    assert long["f"] > short["f"]


def test_rouge_l_ignores_case_and_punctuation():
    """A case-sensitive or punctuation-sensitive port disagrees with the
    shipped metric on every real input, and the disagreement is small enough
    to look like rounding."""
    a = rouge_l("The Cat, sat.", "the cat sat")
    b = rouge_l("the cat sat", "the cat sat")
    assert a["f"] == pytest.approx(b["f"])


def test_rouge_l_empty_inputs_do_not_divide_by_zero():
    assert rouge_l("", "the cat")["f"] == 0.0
    assert rouge_l("the cat", "")["f"] == 0.0


