def test_bootstrap_is_deterministic_for_a_seed():
    data = [0.1, 0.4, 0.35, 0.8, 0.2, 0.9, 0.3, 0.6]
    assert bootstrap_ci(data, 500, seed=7) == bootstrap_ci(data, 500, seed=7)


def test_bootstrap_changes_with_the_seed():
    data = [0.1, 0.4, 0.35, 0.8, 0.2, 0.9, 0.3, 0.6]
    assert bootstrap_ci(data, 500, seed=7) != bootstrap_ci(data, 500, seed=8)


def test_bootstrap_contains_the_mean_and_brackets_it():
    data = [0.10, 0.40, 0.35, 0.80, 0.20, 0.90, 0.30, 0.60]
    mean = sum(data) / len(data)
    lo, hi = bootstrap_ci(data, 2000, seed=3)
    assert lo < mean < hi
    assert 0.0 <= lo <= hi <= 1.0


def test_bootstrap_narrows_with_more_data():
    """Lesson 4.4: the interval halves only when you quadruple the sample."""
    import statistics
    rng = random.Random(1)
    small = [rng.random() for _ in range(20)]
    large = small * 8
    def width(v):
        lo, hi = bootstrap_ci(v, 800, seed=5)
        return hi - lo
    assert width(large) < width(small) * 0.75


def test_bootstrap_raises_on_empty():
    with pytest.raises(ValueError):
        bootstrap_ci([], 100, seed=1)



