// Generate the parity fixtures that labs/common/tests/test_parity.py checks
// against. Every value here is produced by simulations/common/stats.js, so the
// Python package is proven to agree with the engine the browser labs use
// rather than with a hand-copied table.
//
// Note the shape: the JavaScript engine takes {human, judge} objects, not
// tuples. Getting that wrong makes every pair look like a true negative, and
// the confusion matrix comes out plausible and wrong.
//
// Run:  node build/parity-fixtures.mjs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import {
  wilson, confusion, tpr, tnr, cohensKappa, correctedPassRate, pairedComparison,
} from "../simulations/common/stats.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const D = JSON.parse(readFileSync(join(ROOT, "datasets/support.json"), "utf8"));
const byId = new Map(D.items.map((i) => [i.id, i]));

// v1padded is the tuned answer with two extra sentences: same content, so it
// carries v1's human label. The dataset has no human.v1padded, and borrowing
// it explicitly here keeps that fact in one place.
const LABEL_FOR = { v1padded: "v1" };

const pairsFor = (judgeId, variant, ids) =>
  ids.map((id) => ({
    human: byId.get(id).human[LABEL_FOR[variant] ?? variant].label,
    judge: D.runs[judgeId][`${id}|${variant}`][0],
  }));

const out = {
  _note: "Generated by build/parity-fixtures.mjs from simulations/common/stats.js. Do not edit.",
  wilson: {},
  confusion: {},
  corrected: {},
  paired: {},
};

// --- Wilson, on a spread of sizes including the degenerate ones -------------
for (const [k, n] of [[0, 10], [6, 10], [27, 40], [38, 57], [94, 94], [1, 3]]) {
  const w = wilson(k, n);
  out.wilson[`${k}/${n}`] = { point: w.point, lo: w.lo, hi: w.hi };
}

// --- Confusion and kappa on the judges the lessons quote ---------------------
for (const cfg of ["c-plain-3b", "c-rubric-3b", "c-rubric-7b", "c-rubric-1.7b-self"]) {
  for (const variant of ["v1", "v2", "v3"]) {
    const c = confusion(pairsFor(cfg, variant, D.dev_ids));
    out.confusion[`${c.tp}/${c.fp}/${c.fn}/${c.tn}`] = {
      kappa: cohensKappa(c), tpr: tpr(c), tnr: tnr(c), accuracy: c.accuracy ?? null,
    };
  }
}

// --- The Rogan-Gladen correction, including the unstable case ---------------
for (const cfg of ["c-plain-3b", "c-rubric-3b", "c-plain-0.6b", "c-step-7b"]) {
  const c = confusion(pairsFor(cfg, "v1", D.dev_ids));
  const a = tpr(c), b = tnr(c);
  if (a === null || b === null) { console.log(`  (skipping ${cfg}: tpr=${a} tnr=${b})`); continue; }
  const observed = (c.tp + c.fp) / c.n;
  const corr = correctedPassRate(observed, a, b);
  // Normalise the camelCase field name to the Python spelling, so the test
  // reads the same on both sides.
  out.corrected[`${observed.toFixed(6)}/${a.toFixed(6)}/${b.toFixed(6)}`] = corr && {
    value: corr.value,
    stable: corr.stable,
    out_of_range: corr.outOfRange,
  };
}

// --- The paired comparison --------------------------------------------------
// v1padded carries v1's human label (same content, different length), so it
// has to borrow it explicitly — there is no human.v1padded in the dataset.
for (const [a, b] of [["v1", "v2"], ["v1", "v3"], ["v2", "v3"], ["v1", "v1padded"]]) {
  const pa = pairsFor("c-rubric-3b", a, D.dev_ids);
  const pb = pairsFor("c-rubric-3b", b, D.dev_ids);
  const label = (p) => ({ ...p, human: p.human });
  const r = pairedComparison(pa.map(label), pb.map(label), { resamples: 0 });
  const key = `${pa.reduce((s, p) => s + p.judge, 0)}/${pb.reduce((s, p) => s + p.judge, 0)}/${pa.length}`;
  out.paired[key] = { delta: r.delta, fixed: r.fixed, broke: r.broke, ties: r.ties, p: r.pValue };
}

const target = join(ROOT, "labs/common/tests/parity_fixtures.json");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, JSON.stringify(out, null, 1) + "\n", "utf8");
console.log(`wrote ${target.replace(ROOT + "\\", "")}`);
console.log(`  wilson ${Object.keys(out.wilson).length}, confusion ${Object.keys(out.confusion).length}, ` +
  `corrected ${Object.keys(out.corrected).length}, paired ${Object.keys(out.paired).length}`);

